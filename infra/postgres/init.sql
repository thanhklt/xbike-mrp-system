CREATE TABLE "GiaoDichKho" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "mat_hang_id" int NOT NULL,
  "loai_giao_dich" varchar NOT NULL,
  "so_luong_bien_dong" int NOT NULL,
  "so_luong_ton_sau" int NOT NULL,
  "chi_tiet_phieu_nhap_id" int UNIQUE,
  "chi_tiet_phieu_xuat_id" int UNIQUE,
  "chung_tu_hoan_thanh_sx_id" int UNIQUE,
  "nhan_vien_id" int NOT NULL,
  "posted_at" timestamptz NOT NULL DEFAULT (now()),
  CONSTRAINT "ck_giao_dich_kho_loai" CHECK (loai_giao_dich IN ('nhap_linh_kien', 'xuat_linh_kien', 'nhap_san_pham_san_xuat', 'xuat_thanh_pham')),
  CONSTRAINT "ck_giao_dich_ton_sau" CHECK (so_luong_ton_sau >= 0),
  CONSTRAINT "ck_giao_dich_mot_nguon" CHECK (num_nonnulls(chi_tiet_phieu_nhap_id, chi_tiet_phieu_xuat_id, chung_tu_hoan_thanh_sx_id) = 1),
  CONSTRAINT "ck_giao_dich_loai_dau" CHECK (
    (loai_giao_dich = 'nhap_linh_kien' AND chi_tiet_phieu_nhap_id IS NOT NULL AND so_luong_bien_dong > 0)
    OR (loai_giao_dich IN ('xuat_linh_kien', 'xuat_thanh_pham') AND chi_tiet_phieu_xuat_id IS NOT NULL AND so_luong_bien_dong < 0)
    OR (loai_giao_dich = 'nhap_san_pham_san_xuat' AND chung_tu_hoan_thanh_sx_id IS NOT NULL AND so_luong_bien_dong > 0))
);

