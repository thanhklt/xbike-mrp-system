-- Giao dịch kho chỉ sinh từ chứng từ đã ghi nhận; mặt hàng và lượng khớp chứng từ nguồn.
-- Không tự cộng/trừ MatHang.so_luong_ton: backend cập nhật tồn, so_luong_ton_sau, chứng từ và audit cùng transaction.
CREATE FUNCTION kiem_tra_nguon_giao_dich() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_mat_hang int; v_luong int; v_trang_thai text; v_loai text;
BEGIN
  IF NEW.chi_tiet_phieu_nhap_id IS NOT NULL THEN
    SELECT c.mat_hang_id, c.so_luong, p.trang_thai INTO v_mat_hang, v_luong, v_trang_thai
    FROM "ChiTietPhieuNhap" c JOIN "PhieuNhap" p ON p.id = c.phieu_nhap_id
    WHERE c.id = NEW.chi_tiet_phieu_nhap_id;
    IF v_trang_thai IS DISTINCT FROM 'hoan_thanh' THEN
      RAISE EXCEPTION 'Phiếu nhập chưa hoàn tất hoặc không tồn tại'; END IF;
  ELSIF NEW.chi_tiet_phieu_xuat_id IS NOT NULL THEN
    SELECT c.mat_hang_id, -c.so_luong, p.trang_thai, p.loai_phieu INTO v_mat_hang, v_luong, v_trang_thai, v_loai
    FROM "ChiTietPhieuXuat" c JOIN "PhieuXuat" p ON p.id = c.phieu_xuat_id
    WHERE c.id = NEW.chi_tiet_phieu_xuat_id;
    IF v_trang_thai IS DISTINCT FROM 'da_duyet' OR v_loai IS DISTINCT FROM NEW.loai_giao_dich THEN
      RAISE EXCEPTION 'Phiếu xuất chưa duyệt hoặc sai loại giao dịch'; END IF;
  ELSIF NEW.chung_tu_hoan_thanh_sx_id IS NOT NULL THEN
    SELECT y.mat_hang_id, c.so_luong_hoan_thanh, c.trang_thai INTO v_mat_hang, v_luong, v_trang_thai
    FROM "ChungTuHoanThanhSx" c JOIN "YeuCauSanXuat" y ON y.id = c.yeu_cau_san_xuat_id
    WHERE c.id = NEW.chung_tu_hoan_thanh_sx_id;
    IF v_trang_thai IS DISTINCT FROM 'da_duyet' THEN
      RAISE EXCEPTION 'Chứng từ hoàn thành chưa duyệt'; END IF;
  ELSE
    RAISE EXCEPTION 'Giao dịch thiếu chứng từ nguồn';
  END IF;
  IF NEW.mat_hang_id IS DISTINCT FROM v_mat_hang OR NEW.so_luong_bien_dong IS DISTINCT FROM v_luong THEN
    RAISE EXCEPTION 'Mặt hàng hoặc lượng giao dịch không khớp chứng từ nguồn'; END IF;
  RETURN NEW;
END $$;
