CREATE TABLE "VaiTro" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ma_vai_tro" varchar UNIQUE NOT NULL,
  "ten_vai_tro" varchar NOT NULL,
  "mo_ta" varchar(255),
  CONSTRAINT "ck_vai_tro_ma_vai_tro" CHECK (ma_vai_tro IN ('quan_tri_vien', 'quan_ly', 'nhan_vien'))
);

CREATE TABLE "NhanVien" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "vai_tro_id" int NOT NULL,
  "ten_dang_nhap" varchar UNIQUE NOT NULL,
  "mat_khau" varchar NOT NULL,
  "ma_nhan_vien" varchar UNIQUE NOT NULL,
  "ho_ten" varchar,
  "ngay_sinh" date,
  "so_dien_thoai" varchar,
  "email" varchar,
  "ngay_vao_lam" date,
  "he_so_luong" decimal(5,2),
  "trang_thai" varchar NOT NULL DEFAULT 'hoat_dong',
  "phien_ban_dang_nhap" int NOT NULL DEFAULT 0,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  CONSTRAINT "ck_nhan_vien_trang_thai" CHECK (trang_thai IN ('hoat_dong', 'bi_khoa')),
  CONSTRAINT "ck_nhan_vien_he_so_luong" CHECK (he_so_luong >= 0),
  CONSTRAINT "ck_nhan_vien_phien_ban_dang_nhap" CHECK (phien_ban_dang_nhap >= 0),
  CONSTRAINT "ck_nhan_vien_ma" CHECK (ma_nhan_vien ~ '^NV-[0-9]{6}$' AND right(ma_nhan_vien, 6) <> '000000')
);

-- =====================================================================
-- catalog
-- =====================================================================

CREATE TABLE "NhaCungCap" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ma_ncc" varchar UNIQUE NOT NULL,
  "ten_ncc" varchar NOT NULL,
  "so_dien_thoai" varchar NOT NULL,
  "dia_chi" varchar NOT NULL,
  "phuong" varchar NOT NULL,
  "tinh" varchar NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  CONSTRAINT "ck_nha_cung_cap_ma" CHECK (ma_ncc ~ '^NCC-[0-9]{6}$' AND right(ma_ncc, 6) <> '000000'),
  CONSTRAINT "ck_nha_cung_cap_thong_tin" CHECK (
    btrim(ten_ncc) <> '' AND btrim(so_dien_thoai) <> '' AND btrim(dia_chi) <> ''
    AND btrim(phuong) <> '' AND btrim(tinh) <> '')
);

CREATE TABLE "MatHang" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ma_mat_hang" varchar UNIQUE NOT NULL,
  "ten_mat_hang" varchar NOT NULL,
  "sku" varchar UNIQUE NOT NULL,
  "loai_mat_hang" varchar NOT NULL,
  "don_vi_tinh" varchar NOT NULL,
  "mau_sac" varchar,
  "mo_ta" varchar,
  "don_gia" bigint NOT NULL,
  "is_active" bool NOT NULL DEFAULT true,
  "so_luong_ton" int NOT NULL DEFAULT 0,
  "so_luong_dang_giu" int NOT NULL DEFAULT 0,
  "so_luong_con_dung" int GENERATED ALWAYS AS (so_luong_ton - so_luong_dang_giu) STORED,
  "ton_kho_updated_at" timestamptz,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  CONSTRAINT "ck_mat_hang_loai" CHECK (loai_mat_hang IN ('thanh_pham', 'linh_kien')),
  CONSTRAINT "ck_mat_hang_active" CHECK (loai_mat_hang = 'thanh_pham' OR is_active),
  CONSTRAINT "ck_mat_hang_ton" CHECK (so_luong_ton >= 0 AND so_luong_dang_giu >= 0 AND so_luong_dang_giu <= so_luong_ton),
  CONSTRAINT "ck_mat_hang_don_gia" CHECK (don_gia >= 0),
  CONSTRAINT "ck_mat_hang_ten" CHECK (ten_mat_hang ~ '[^[:space:]]'),
  CONSTRAINT "ck_mat_hang_don_vi_tinh" CHECK (btrim(don_vi_tinh) <> ''),
  CONSTRAINT "ck_mat_hang_ma" CHECK (ma_mat_hang ~ '^MH-[0-9]{6}$' AND right(ma_mat_hang, 6) <> '000000')
);

-- =====================================================================
-- bom
-- =====================================================================

CREATE TABLE "Bom" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "mat_hang_id" int NOT NULL,
  "version" int NOT NULL,
  "is_active" bool NOT NULL DEFAULT true,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "kich_hoat_gan_nhat_at" timestamptz NOT NULL DEFAULT (now()),
  CONSTRAINT "ck_bom_version" CHECK (version > 0)
);

CREATE TABLE "ChiTietBom" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "bom_id" int NOT NULL,
  "mat_hang_id" int NOT NULL,
  "so_luong" int NOT NULL,
  CONSTRAINT "ck_chi_tiet_bom_so_luong" CHECK (so_luong > 0)
);

-- =====================================================================
-- goods_receipt
-- =====================================================================

CREATE TABLE "PhieuNhap" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ma_phieu_nhap" varchar UNIQUE NOT NULL,
  "nhan_vien_id" int NOT NULL,
  "ncc_id" int NOT NULL,
  "ngay_nhap" date NOT NULL,
  "ghi_chu" text,
  "tong_tien" bigint,
  "trang_thai" varchar NOT NULL DEFAULT 'nhap',
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "updated_at" timestamptz NOT NULL DEFAULT (now()),
  "hoan_thanh_at" timestamptz,
  "nguoi_hoan_thanh_id" int,
  "phien_ban" int NOT NULL DEFAULT 1,
  CONSTRAINT "ck_phieu_nhap_trang_thai" CHECK (trang_thai IN ('nhap', 'hoan_thanh')),
  CONSTRAINT "ck_phieu_nhap_tien" CHECK (tong_tien >= 0),
  CONSTRAINT "ck_phieu_nhap_phien_ban" CHECK (phien_ban > 0),
  CONSTRAINT "ck_phieu_nhap_hoan_thanh" CHECK ((trang_thai = 'hoan_thanh') = (hoan_thanh_at IS NOT NULL AND nguoi_hoan_thanh_id IS NOT NULL)),
  CONSTRAINT "ck_phieu_nhap_ma" CHECK (ma_phieu_nhap ~ '^PN-[0-9]{4}(0[1-9]|1[0-2])-[0-9]{6}$' AND right(ma_phieu_nhap, 6) <> '000000')
);

CREATE TABLE "ChiTietPhieuNhap" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "phieu_nhap_id" int NOT NULL,
  "mat_hang_id" int NOT NULL,
  "so_luong" int NOT NULL,
  "don_gia_thuc" bigint NOT NULL,
  "tong_gia" bigint NOT NULL,
  CONSTRAINT "ck_chi_tiet_phieu_nhap_so_luong" CHECK (so_luong > 0),
  CONSTRAINT "ck_chi_tiet_phieu_nhap_tien" CHECK (don_gia_thuc >= 0 AND tong_gia = so_luong::bigint * don_gia_thuc)
);

-- =====================================================================
-- production
-- =====================================================================

CREATE TABLE "YeuCauSanXuat" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ma_yeu_cau_san_xuat" varchar UNIQUE NOT NULL,
  "loai_yeu_cau" varchar NOT NULL DEFAULT 'dap_ung',
  "mat_hang_id" int NOT NULL,
  "so_luong" int NOT NULL,
  "han_hoan_thanh" date NOT NULL,
  "nhan_vien_id" int NOT NULL,
  "nhan_vien_duoc_giao_id" int NOT NULL,
  "bom_id" int,
  "trang_thai" varchar NOT NULL DEFAULT 'nhap',
  "so_luong_dung_thanh_pham" int,
  "so_luong_can_san_xuat" int,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "updated_at" timestamptz NOT NULL DEFAULT (now()),
  "gui_at" timestamptz,
  "kiem_tra_lan_dau_at" timestamptz,
  "started_at" timestamptz,
  "completed_at" timestamptz,
  "huy_at" timestamptz,
  "nguoi_huy_id" int,
  "ly_do_huy" text,
  "phien_ban" int NOT NULL DEFAULT 1,
  CONSTRAINT "ck_ycsx_trang_thai" CHECK (trang_thai IN ('nhap', 'da_gui', 'cho_bo_sung_linh_kien', 'dang_thuc_hien', 'hoan_thanh', 'da_huy')),
  CONSTRAINT "ck_ycsx_loai" CHECK (loai_yeu_cau IN ('dap_ung', 'cho_kho')),
  CONSTRAINT "ck_ycsx_cho_kho" CHECK (loai_yeu_cau = 'dap_ung' OR COALESCE(so_luong_dung_thanh_pham, 0) = 0),
  CONSTRAINT "ck_ycsx_so_luong" CHECK (so_luong > 0),
  CONSTRAINT "ck_ycsx_phien_ban" CHECK (phien_ban > 0),
  CONSTRAINT "ck_ycsx_bom_chot" CHECK (trang_thai = 'nhap' OR (bom_id IS NOT NULL AND gui_at IS NOT NULL)),
  CONSTRAINT "ck_ycsx_so_luong_chot" CHECK (
    (so_luong_dung_thanh_pham IS NULL AND so_luong_can_san_xuat IS NULL AND kiem_tra_lan_dau_at IS NULL)
    OR (so_luong_dung_thanh_pham >= 0 AND so_luong_can_san_xuat >= 0
        AND so_luong_dung_thanh_pham + so_luong_can_san_xuat = so_luong
        AND kiem_tra_lan_dau_at IS NOT NULL)),
  CONSTRAINT "ck_ycsx_da_kiem_tra" CHECK (trang_thai NOT IN ('cho_bo_sung_linh_kien', 'dang_thuc_hien', 'hoan_thanh') OR so_luong_can_san_xuat IS NOT NULL),
  CONSTRAINT "ck_ycsx_bat_dau" CHECK (started_at IS NULL OR (so_luong_can_san_xuat > 0 AND trang_thai IN ('dang_thuc_hien', 'hoan_thanh'))),
  CONSTRAINT "ck_ycsx_hoan_thanh" CHECK ((trang_thai = 'hoan_thanh') = (completed_at IS NOT NULL)),
  CONSTRAINT "ck_ycsx_huy" CHECK ((trang_thai = 'da_huy') = (huy_at IS NOT NULL AND nguoi_huy_id IS NOT NULL AND COALESCE(btrim(ly_do_huy), '') <> '')),
  CONSTRAINT "ck_ycsx_ma" CHECK (ma_yeu_cau_san_xuat ~ '^YCSX-[0-9]{4}(0[1-9]|1[0-2])-[0-9]{6}$' AND right(ma_yeu_cau_san_xuat, 6) <> '000000')
);

CREATE TABLE "NhuCauLinhKien" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "yeu_cau_san_xuat_id" int NOT NULL,
  "mat_hang_id" int NOT NULL,
  "so_luong_can" int NOT NULL,
  CONSTRAINT "ck_nhu_cau_linh_kien_so_luong" CHECK (so_luong_can > 0)
);

CREATE TABLE "GiuHang" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "yeu_cau_san_xuat_id" int NOT NULL,
  "mat_hang_id" int NOT NULL,
  "loai_giu" varchar NOT NULL,
  "so_luong" int NOT NULL,
  "trang_thai" varchar NOT NULL DEFAULT 'dang_giu',
  "chung_tu_hoan_thanh_sx_id" int,
  "phieu_xuat_id" int,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "ket_thuc_at" timestamptz,
  CONSTRAINT "ck_giu_hang_loai" CHECK (loai_giu IN ('thanh_pham_co_san', 'linh_kien', 'thanh_pham_san_xuat')),
  CONSTRAINT "ck_giu_hang_trang_thai" CHECK (trang_thai IN ('dang_giu', 'da_xuat', 'da_tra')),
  CONSTRAINT "ck_giu_hang_so_luong" CHECK (so_luong > 0),
  CONSTRAINT "ck_giu_hang_ket_thuc" CHECK ((trang_thai = 'dang_giu') = (ket_thuc_at IS NULL)),
  CONSTRAINT "ck_giu_hang_da_xuat" CHECK ((trang_thai = 'da_xuat') = (phieu_xuat_id IS NOT NULL)),
  CONSTRAINT "ck_giu_hang_nguon_sx" CHECK ((loai_giu = 'thanh_pham_san_xuat') = (chung_tu_hoan_thanh_sx_id IS NOT NULL))
);

CREATE TABLE "ChungTuHoanThanhSx" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ma_phieu" varchar UNIQUE NOT NULL,
  "yeu_cau_san_xuat_id" int UNIQUE NOT NULL,
  "so_luong_hoan_thanh" int NOT NULL,
  "nhan_vien_id" int NOT NULL,
  "trang_thai" varchar NOT NULL DEFAULT 'nhap',
  "finish_time" timestamptz,
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "updated_at" timestamptz NOT NULL DEFAULT (now()),
  "nguoi_xu_ly_id" int,
  "xu_ly_at" timestamptz,
  "ly_do_tu_choi" text,
  "phien_ban" int NOT NULL DEFAULT 1,
  CONSTRAINT "ck_htsx_trang_thai" CHECK (trang_thai IN ('nhap', 'cho_duyet', 'da_duyet', 'tu_choi')),
  CONSTRAINT "ck_htsx_so_luong" CHECK (so_luong_hoan_thanh > 0),
  CONSTRAINT "ck_htsx_phien_ban" CHECK (phien_ban > 0),
  CONSTRAINT "ck_htsx_finish_time" CHECK (trang_thai = 'nhap' OR finish_time IS NOT NULL),
  CONSTRAINT "ck_htsx_xu_ly" CHECK (trang_thai NOT IN ('da_duyet', 'tu_choi') OR (nguoi_xu_ly_id IS NOT NULL AND xu_ly_at IS NOT NULL)),
  CONSTRAINT "ck_htsx_ly_do" CHECK (trang_thai <> 'tu_choi' OR COALESCE(btrim(ly_do_tu_choi), '') <> ''),
  CONSTRAINT "ck_htsx_ma" CHECK (ma_phieu ~ '^HTSX-[0-9]{4}(0[1-9]|1[0-2])-[0-9]{6}$' AND right(ma_phieu, 6) <> '000000')
);

