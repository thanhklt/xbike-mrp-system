CREATE TABLE "PhieuXuat" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ma_phieu_xuat" varchar UNIQUE NOT NULL,
  "nhan_vien_id" int NOT NULL,
  "loai_phieu" varchar NOT NULL,
  "yeu_cau_san_xuat_id" int NOT NULL,
  "tong_tien" bigint,
  "trang_thai" varchar NOT NULL DEFAULT 'nhap',
  "created_at" timestamptz NOT NULL DEFAULT (now()),
  "updated_at" timestamptz NOT NULL DEFAULT (now()),
  "gui_at" timestamptz,
  "nguoi_xu_ly_id" int,
  "xu_ly_at" timestamptz,
  "ly_do_tu_choi" text,
  "phien_ban" int NOT NULL DEFAULT 1,
  CONSTRAINT "ck_px_loai_phieu" CHECK (loai_phieu IN ('xuat_linh_kien', 'xuat_thanh_pham')),
  CONSTRAINT "ck_px_trang_thai" CHECK (trang_thai IN ('nhap', 'cho_duyet', 'da_duyet', 'tu_choi')),
  CONSTRAINT "ck_px_phien_ban" CHECK (phien_ban > 0),
  CONSTRAINT "ck_px_gui" CHECK (trang_thai = 'nhap' OR gui_at IS NOT NULL),
  CONSTRAINT "ck_px_xu_ly" CHECK (trang_thai NOT IN ('da_duyet', 'tu_choi') OR (nguoi_xu_ly_id IS NOT NULL AND xu_ly_at IS NOT NULL)),
  CONSTRAINT "ck_px_ly_do" CHECK (trang_thai <> 'tu_choi' OR COALESCE(btrim(ly_do_tu_choi), '') <> ''),
  CONSTRAINT "ck_px_tien" CHECK (tong_tien >= 0),
  CONSTRAINT "ck_px_tien_duyet" CHECK (trang_thai <> 'da_duyet' OR tong_tien IS NOT NULL),
  CONSTRAINT "ck_px_ma" CHECK (ma_phieu_xuat ~ '^PX-[0-9]{4}(0[1-9]|1[0-2])-[0-9]{6}$' AND right(ma_phieu_xuat, 6) <> '000000')
);

CREATE TABLE "ChiTietPhieuXuat" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "phieu_xuat_id" int NOT NULL,
  "mat_hang_id" int NOT NULL,
  "so_luong" int NOT NULL,
  "don_gia_thuc" bigint,
  "tong_gia" bigint,
  CONSTRAINT "ck_chi_tiet_phieu_xuat_so_luong" CHECK (so_luong > 0),
  CONSTRAINT "ck_chi_tiet_phieu_xuat_tien" CHECK (
    (don_gia_thuc IS NULL AND tong_gia IS NULL)
    OR (don_gia_thuc >= 0 AND tong_gia = so_luong::bigint * don_gia_thuc))
);

