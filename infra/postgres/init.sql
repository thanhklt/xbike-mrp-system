-- Phiên bản công thức không bao giờ sửa: chỉ được đổi is_active, kich_hoat_gan_nhat_at; không xóa.
-- Dòng định mức chỉ được thêm khi phiên bản chưa được chốt vào yêu cầu sản xuất nào; không sửa, không xóa.
CREATE FUNCTION bao_ve_bom() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_TABLE_NAME = 'Bom' THEN
    IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'Không được xóa phiên bản công thức'; END IF;
    IF ROW(NEW.id, NEW.mat_hang_id, NEW.version, NEW.created_at)
       IS DISTINCT FROM ROW(OLD.id, OLD.mat_hang_id, OLD.version, OLD.created_at) THEN
      RAISE EXCEPTION 'Phiên bản công thức chỉ được đổi trạng thái đang dùng'; END IF;
    RETURN NEW;
  END IF;
  IF TG_OP <> 'INSERT' THEN RAISE EXCEPTION 'Không được sửa/xóa dòng định mức; hãy tạo phiên bản mới'; END IF;
  PERFORM 1 FROM "Bom" WHERE id = NEW.bom_id FOR UPDATE;
  IF EXISTS (SELECT 1 FROM "YeuCauSanXuat" WHERE bom_id = NEW.bom_id) THEN
    RAISE EXCEPTION 'Phiên bản công thức đã chốt vào yêu cầu sản xuất, không thêm dòng'; END IF;
  RETURN NEW;
END $$;
