-- Chặn thêm, sửa hoặc chuyển dòng ra/vào chứng từ đã ghi nhận.
CREATE FUNCTION bao_ve_dong_chung_tu() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_id int; v_state text; v_ids int[] := '{}';
BEGIN
  IF TG_OP <> 'INSERT' THEN v_ids := array_append(v_ids, (to_jsonb(OLD) ->> TG_ARGV[1])::int); END IF;
  IF TG_OP <> 'DELETE' THEN v_ids := array_append(v_ids, (to_jsonb(NEW) ->> TG_ARGV[1])::int); END IF;
  FOREACH v_id IN ARRAY v_ids LOOP
    EXECUTE format('SELECT trang_thai FROM %I WHERE id = $1 FOR UPDATE', TG_ARGV[0]) INTO v_state USING v_id;
    IF v_state = ANY(string_to_array(TG_ARGV[2], ',')) THEN
      RAISE EXCEPTION 'Không được thay đổi dòng của chứng từ đã ghi nhận'; END IF;
  END LOOP;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END $$;
