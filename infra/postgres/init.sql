-- Yêu cầu sản xuất: sửa/xóa chỉ khi nháp; sau khi gửi không đổi thành phẩm, số lượng, hạn, người giao/nhận, công thức đã chốt;
-- số lượng chốt ở lần kiểm tra đầu không đổi; yêu cầu Hoàn thành / Đã hủy không thao tác thêm.
CREATE FUNCTION bao_ve_yeu_cau_san_xuat() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.trang_thai <> 'nhap' THEN RAISE EXCEPTION 'Chỉ xóa được yêu cầu sản xuất còn nháp'; END IF;
    RETURN OLD;
  END IF;
  IF OLD.trang_thai IN ('hoan_thanh', 'da_huy') THEN
    RAISE EXCEPTION 'Yêu cầu sản xuất đã kết thúc, không thao tác thêm'; END IF;
  IF NEW.id IS DISTINCT FROM OLD.id OR NEW.ma_yeu_cau_san_xuat IS DISTINCT FROM OLD.ma_yeu_cau_san_xuat THEN
    RAISE EXCEPTION 'Không được sửa mã yêu cầu sản xuất'; END IF;
  IF OLD.trang_thai <> 'nhap' AND ROW(NEW.loai_yeu_cau, NEW.mat_hang_id, NEW.so_luong, NEW.han_hoan_thanh, NEW.nhan_vien_id,
       NEW.nhan_vien_duoc_giao_id, NEW.bom_id, NEW.gui_at)
     IS DISTINCT FROM ROW(OLD.loai_yeu_cau, OLD.mat_hang_id, OLD.so_luong, OLD.han_hoan_thanh, OLD.nhan_vien_id,
       OLD.nhan_vien_duoc_giao_id, OLD.bom_id, OLD.gui_at) THEN
    RAISE EXCEPTION 'Yêu cầu đã gửi không được đổi loại, thành phẩm, số lượng, hạn, nhân viên hoặc công thức'; END IF;
  IF OLD.kiem_tra_lan_dau_at IS NOT NULL AND ROW(NEW.so_luong_dung_thanh_pham, NEW.so_luong_can_san_xuat, NEW.kiem_tra_lan_dau_at)
     IS DISTINCT FROM ROW(OLD.so_luong_dung_thanh_pham, OLD.so_luong_can_san_xuat, OLD.kiem_tra_lan_dau_at) THEN
    RAISE EXCEPTION 'Số lượng đã chốt ở lần kiểm tra đầu không được đổi'; END IF;
  RETURN NEW;
END $$;
