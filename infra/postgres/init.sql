-- Mã mặt hàng do hệ thống cấp từ id (chốt 14/11/2026): MH-NNNNNN. Giá trị client gửi lên bị bỏ qua.
-- Mã và loại mặt hàng bất biến sau khi tạo.
CREATE FUNCTION cap_ma_mat_hang() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.id > 999999 THEN RAISE EXCEPTION 'Hết dải mã mặt hàng MH-NNNNNN'; END IF;
    NEW.ma_mat_hang := 'MH-' || lpad(NEW.id::text, 6, '0');
  ELSE
    IF NEW.id IS DISTINCT FROM OLD.id OR NEW.ma_mat_hang IS DISTINCT FROM OLD.ma_mat_hang THEN
      RAISE EXCEPTION 'Không được sửa mã mặt hàng'; END IF;
    IF NEW.loai_mat_hang IS DISTINCT FROM OLD.loai_mat_hang THEN
      RAISE EXCEPTION 'Không được đổi loại mặt hàng'; END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_mat_hang_ma BEFORE INSERT OR UPDATE ON "MatHang"
FOR EACH ROW EXECUTE FUNCTION cap_ma_mat_hang();

