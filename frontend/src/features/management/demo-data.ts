function seedOrder(
  id: string,
  requestId: string,
  outputId: string,
  quantity: number,
  parentOrderId: string | null,
): WorkOrder {
  const bom = activeBom(seedBoms, outputId);
  return {
    id,
    code: `LSX-202611-${id.slice(-3).padStart(6, "0")}`,
    requestId,
    kind: outputId === "wheel" ? "wheel" : "bike",
    quantity,
    assigneeId: outputId === "wheel" ? "employee-huy" : "employee-nam",
    bomId: bom.id,
    parentOrderId,
    outputId,
    createdAt: seedAt,
    status: "da_gui",
    demand: materialDemand(seedItems, bom, quantity).map(({ itemId, perUnit, required }) => ({
      itemId,
      perUnit,
      required,
    })),
  };
}
